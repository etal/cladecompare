"""Visualize CladeCompare output file(s) in an HTML page.

If given one file:
    Display foreground and background consensus sequences as 2 rows, wrapped.
    Color of foreground cells corresponds to p-value (#stars).

If given multiple files:
    Display each file's foreground consensus sequence as one row, wrapped.
    The files must number the same columns, as the files that cladecompare
    writes for three or more alignments do.
    The background, which differs between those files, is not shown; a
    column whose background consensus is a gap is colored as an insert.
    Color of foreground cells corresponds to p-value (#stars).

"""

import argparse

from cladecomparelib import configure_logging
from cladecomparelib.report import do_multi, do_single, html_page


def main():
    configure_logging()

    AP = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    AP.add_argument(
        "outfiles", nargs="+", help="Output file(s) generated by cladecompare"
    )
    AP.add_argument(
        "-p", "--pattern", help="Pattern file (.pttrn) generated by cladecompare"
    )
    AP.add_argument("-o", "--output", help="HTML output file name. (Default: stdout)")
    args = AP.parse_args()

    if len(args.outfiles) == 1:
        title, contents = do_single(args.outfiles[0], args.pattern)
    else:
        title, contents = do_multi(args.outfiles, args.pattern)
    html_report = html_page(title, contents)

    if args.output:
        with open(args.output, "w") as handle:
            handle.write(html_report)
    else:
        print(html_report)
